// Exports the database structure (tables, views, triggers, procedures) to db/schema.sql — no data.
// Run after any schema change:  npm run db:export-schema
// Rebuild an empty database from it in MySQL Workbench, or:  mysql -u root -p <database> < db/schema.sql
const fs = require('fs');
const path = require('path');
const db = require('./db.js');

// Strip machine-specific details so the file is portable and diffs stay clean
const clean = (sql) => sql
  .replace(/\s*DEFINER=`[^`]+`@`[^`]+`/g, '')
  .replace(/ AUTO_INCREMENT=\d+/g, '')
  .replace(/ ALGORITHM=UNDEFINED/g, '')
  .replace(/ SQL SECURITY DEFINER/g, '');

(async () => {
  const [[{ dbName }]] = await db.query('SELECT DATABASE() AS dbName');
  const out = [
    '-- Schema for the online examination system (structure only, no data).',
    '-- Generated by db/export-schema.js — do not edit by hand; change the database, then re-export.',
    '-- Includes every migration in db/migrations up to the time of export.',
    '',
    'SET FOREIGN_KEY_CHECKS = 0;',
    ''
  ];

  // Tables (FK checks are off above, so order doesn't matter)
  const [tables] = await db.query(
    `SELECT TABLE_NAME AS name FROM information_schema.TABLES
     WHERE TABLE_SCHEMA = ? AND TABLE_TYPE = 'BASE TABLE' ORDER BY TABLE_NAME`, [dbName]);
  for (const { name } of tables) {
    const [[row]] = await db.query(`SHOW CREATE TABLE \`${name}\``);
    out.push(`${clean(row['Create Table'])};`, '');
  }

  // Views, ordered so a view is created after any view it reads from
  const [views] = await db.query(
    `SELECT TABLE_NAME AS name FROM information_schema.VIEWS WHERE TABLE_SCHEMA = ? ORDER BY TABLE_NAME`, [dbName]);
  const [usage] = await db.query(
    `SELECT VIEW_NAME AS view_name, TABLE_NAME AS used FROM information_schema.VIEW_TABLE_USAGE WHERE VIEW_SCHEMA = ?`, [dbName]);
  const viewNames = new Set(views.map(v => v.name));
  const pending = views.map(v => v.name);
  const done = new Set();
  while (pending.length) {
    const i = pending.findIndex(v => usage.every(u => u.view_name !== v || !viewNames.has(u.used) || done.has(u.used)));
    if (i === -1) throw new Error(`Circular view dependency among: ${pending.join(', ')}`);
    const [name] = pending.splice(i, 1);
    const [[row]] = await db.query(`SHOW CREATE VIEW \`${name}\``);
    out.push(`${clean(row['Create View'])};`, '');
    done.add(name);
  }

  out.push('SET FOREIGN_KEY_CHECKS = 1;', '', 'DELIMITER $$', '');

  const [triggers] = await db.query(
    `SELECT TRIGGER_NAME AS name FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA = ? ORDER BY EVENT_OBJECT_TABLE, TRIGGER_NAME`, [dbName]);
  for (const { name } of triggers) {
    const [[row]] = await db.query(`SHOW CREATE TRIGGER \`${name}\``);
    out.push(`${clean(row['SQL Original Statement'])}$$`, '');
  }

  const [routines] = await db.query(
    `SELECT ROUTINE_NAME AS name, ROUTINE_TYPE AS type FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA = ? ORDER BY ROUTINE_NAME`, [dbName]);
  for (const { name, type } of routines) {
    const [[row]] = await db.query(`SHOW CREATE ${type} \`${name}\``);
    out.push(`${clean(row[type === 'PROCEDURE' ? 'Create Procedure' : 'Create Function'])}$$`, '');
  }

  out.push('DELIMITER ;', '');

  const file = path.join(__dirname, 'schema.sql');
  fs.writeFileSync(file, out.join('\n'));
  console.log(`Wrote ${file}: ${tables.length} tables, ${views.length} views, ${triggers.length} triggers, ${routines.length} routines`);
  process.exit(0);
})().catch(err => {
  console.error('Schema export failed:', err.message);
  process.exit(1);
});
